// مولّدات «تحدّي الأرقام»: مسائل عددية جديدة في كل مرة، تُصحَّح آليًا.
// كل مولّد يعيد سؤالًا بصيغة محرّك الأسئلة. القيم مختارة لتكون أرقامها نظيفة كأرقام الكتاب.
import { sci } from './math.js';

const pick = (a) => a[(Math.random() * a.length) | 0];
const E0 = 8.85e-12;
const fmt = (x) => sci(x, 3);
const uid = () => 'g' + Math.random().toString(36).slice(2, 9);

const G = {
  // السعة C = Q/ΔV
  cap_q() {
    const C = pick([2, 3, 4, 5, 6, 8, 10, 12, 20, 25]) * 1e-6, V = pick([10, 12, 20, 24, 50, 100, 120, 200]);
    const Q = C * V;
    return { q: `متسعة سعتها $${C * 1e6} μF$ ربطت بين قطبي بطارية فرق الجهد بينهما $${V} V$. احسب مقدار الشحنة المختزنة في أي من صفيحتيها بوحدة الميكروكولوم $μC$.`,
      value: Q * 1e6, unit: 'μC', show: `${fmt(Q * 1e6)} μC`, steps: [`Q = C × ΔV`, `Q = ${C * 1e6}×10^{-6} × ${V}`, `Q = ${fmt(Q)} C = ${fmt(Q * 1e6)} μC`] };
  },
  cap_c() {
    const V = pick([6, 12, 20, 24, 50, 100]), C = pick([2, 4, 5, 8, 10, 15, 20]) * 1e-6, Q = C * V;
    return { q: `شحنت متسعة بشحنة مقدارها $${fmt(Q * 1e6)} μC$ عندما كان فرق الجهد بين صفيحتيها $${V} V$. احسب سعتها بوحدة المايكروفاراد $μF$.`,
      value: C * 1e6, unit: 'μF', show: `${C * 1e6} μF`, steps: [`C = \\frac{Q}{ΔV}`, `C = \\frac{${fmt(Q * 1e6)}×10^{-6}}{${V}}`, `C = ${C * 1e6}×10^{-6} F = ${C * 1e6} μF`] };
  },
  // المتسعة ذات الصفيحتين: C = k ε0 A / d
  plates() {
    const A = pick([0.1, 0.2, 0.4, 0.5, 0.8, 1.0, 2.0]), dmm = pick([0.5, 1, 2, 4, 5, 8.85]), k = pick([1, 1, 2, 3, 4, 5]);
    const d = dmm * 1e-3, C = k * E0 * A / d;
    const kTxt = k === 1 ? 'والفراغ بينهما هواء' : `وبينهما عازل ثابت عزله $k = ${k}$`;
    return { q: `متسعة ذات صفيحتين متوازيتين مساحة كل منهما $${A} m^{2}$ والبعد بينهما $${dmm} mm$ ${kTxt}. احسب سعتها بوحدة البيكوفاراد $pF$. (علمًا أن $ε_{o} = 8.85 × 10^{-12} C^{2}/N.m^{2}$)`,
      value: C * 1e12, unit: 'pF', show: `${fmt(C * 1e12)} pF`, tol: 0.03,
      steps: [`C = \\frac{k ε_{o} A}{d}`, `C = \\frac{${k} × 8.85×10^{-12} × ${A}}{${dmm}×10^{-3}}`, `C = ${fmt(C)} F = ${fmt(C * 1e12)} pF`] };
  },
  // إدخال عازل والمتسعة مفصولة عن المصدر
  diel_off() {
    const k = pick([2, 3, 4, 5, 6]), V = k * pick([10, 20, 25, 30, 40, 50]);
    return { q: `متسعة مشحونة فرق الجهد بين صفيحتيها $${V} V$ فصلت عن المصدر، ثم أدخل بين صفيحتيها لوح عازل ثابت عزله $k = ${k}$ يملأ الحيز بينهما. احسب فرق الجهد الجديد بين الصفيحتين.`,
      value: V / k, unit: 'V', show: `${fmt(V / k)} V`, steps: ['الشحنة ثابتة لأن المتسعة مفصولة عن المصدر', `ΔV_{k} = \\frac{ΔV}{k}`, `ΔV_{k} = \\frac{${V}}{${k}} = ${fmt(V / k)} V`] };
  },
  diel_on() {
    const k = pick([2, 3, 4, 5]), C = pick([2, 4, 5, 10, 20]), V = pick([12, 20, 50, 100]);
    const Q2 = k * C * V;
    return { q: `متسعة سعتها $${C} μF$ ربطت بمصدر فرق جهده $${V} V$ وبقيت متصلة به، ثم أدخل بين صفيحتيها عازل ثابت عزله $k = ${k}$. احسب الشحنة المختزنة فيها بعد إدخال العازل بوحدة $μC$.`,
      value: Q2, unit: 'μC', show: `${fmt(Q2)} μC`, steps: ['فرق الجهد ثابت لأن المتسعة متصلة بالمصدر', `C_{k} = k C = ${k} × ${C} = ${k * C} μF`, `Q_{k} = C_{k} ΔV = ${k * C} × ${V} = ${fmt(Q2)} μC`] };
  },
  // الربط على التوالي
  series() {
    const sets = [[6, 3], [12, 6], [4, 4], [10, 15], [3, 6], [20, 30], [12, 4], [6, 12, 4], [3, 6, 6], [10, 10, 5]];
    const cs = pick(sets), inv = cs.reduce((s, c) => s + 1 / c, 0), Ce = 1 / inv;
    const names = cs.map((c, i) => `$C_{${i + 1}} = ${c} μF$`).join(' و');
    return { q: `ربطت المتسعات ${names} على التوالي. احسب السعة المكافئة للمجموعة بوحدة $μF$.`,
      value: Ce, unit: 'μF', show: `${fmt(Ce)} μF`, steps: [`\\frac{1}{C_{eq}} = ${cs.map((c, i) => `\\frac{1}{C_{${i + 1}}}`).join(' + ')}`, `\\frac{1}{C_{eq}} = ${cs.map((c) => `\\frac{1}{${c}}`).join(' + ')}`, `C_{eq} = ${fmt(Ce)} μF`] };
  },
  parallel() {
    const cs = pick([[2, 3], [4, 6], [5, 10, 15], [12, 8], [3, 6, 9], [20, 30]]), Ce = cs.reduce((a, b) => a + b, 0), V = pick([10, 12, 20, 50]);
    return { q: `ربطت المتسعات ${cs.map((c, i) => `$C_{${i + 1}} = ${c} μF$`).join(' و')} على التوازي، وربطت المجموعة بمصدر فرق جهده $${V} V$. احسب الشحنة الكلية المختزنة في المجموعة بوحدة $μC$.`,
      value: Ce * V, unit: 'μC', show: `${fmt(Ce * V)} μC`, steps: [`C_{eq} = ${cs.map((c, i) => `C_{${i + 1}}`).join(' + ')} = ${cs.join(' + ')} = ${Ce} μF`, `Q_{T} = C_{eq} × ΔV = ${Ce} × ${V} = ${fmt(Ce * V)} μC`] };
  },
  series_v() {
    const [a, b] = pick([[6, 3], [12, 6], [4, 12], [2, 8], [10, 40]]), V = pick([12, 24, 30, 60, 90]);
    const Ce = a * b / (a + b), Q = Ce * V, V1 = Q / a;
    return { q: `متسعتان $C_{1} = ${a} μF$ و$C_{2} = ${b} μF$ مربوطتان على التوالي بين قطبي بطارية فرق الجهد بينهما $${V} V$. احسب فرق الجهد بين صفيحتي المتسعة الأولى $C_{1}$.`,
      value: V1, unit: 'V', show: `${fmt(V1)} V`, steps: [`C_{eq} = \\frac{C_{1} C_{2}}{C_{1} + C_{2}} = \\frac{${a} × ${b}}{${a + b}} = ${fmt(Ce)} μF`, `Q = C_{eq} ΔV = ${fmt(Ce)} × ${V} = ${fmt(Q)} μC`, 'الشحنة متساوية في المتسعات المربوطة على التوالي', `ΔV_{1} = \\frac{Q}{C_{1}} = \\frac{${fmt(Q)}}{${a}} = ${fmt(V1)} V`] };
  },
  // جهد كرة موصلة معزولة V = kQ/r
  sphere() {
    const r = pick([5, 10, 20, 30, 50]), Qn = pick([1, 2, 3, 4, 5, 6]), V = 9e9 * Qn * 1e-9 / (r / 100);
    return { q: `كرة موصلة معزولة نصف قطرها $${r} cm$ شحنت بشحنة مقدارها $${Qn} nC$. احسب جهدها بوحدة الفولط، علمًا أن $k = 9 × 10^{9} N.m^{2}/C^{2}$.`,
      value: V, unit: 'V', show: `${fmt(V)} V`, steps: [`V = k\\frac{Q}{r}`, `V = 9×10^{9} × \\frac{${Qn}×10^{-9}}{${r / 100}}`, `V = ${fmt(V)} V`] };
  },
  // أعظم تيار شحن لحظة إغلاق الدائرة I = ΔV/R
  rc_i() {
    const V = pick([6, 12, 20, 24, 50, 100]), R = pick([2, 4, 5, 10, 20, 50]);
    return { q: `دائرة تيار مستمر فيها متسعة غير مشحونة ومقاومة $${R} Ω$ وبطارية فرق الجهد بين قطبيها $${V} V$. احسب المقدار الأعظم لتيار الشحن لحظة إغلاق المفتاح بوحدة الأمبير.`,
      value: V / R, unit: 'A', show: `${fmt(V / R)} A`, steps: ['لحظة إغلاق الدائرة يكون فرق الجهد بين صفيحتي المتسعة صفرًا، فيكون تيار الشحن بمقداره الأعظم', `I = \\frac{ΔV_{battery}}{R}`, `I = \\frac{${V}}{${R}} = ${fmt(V / R)} A`] };
  },
  // الطاقة المختزنة
  energy() {
    const C = pick([2, 4, 5, 10, 20, 50]), V = pick([10, 20, 50, 100, 200]);
    const PE = 0.5 * C * 1e-6 * V * V;
    return { q: `متسعة سعتها $${C} μF$ شحنت حتى صار فرق الجهد بين صفيحتيها $${V} V$. احسب الطاقة المختزنة في مجالها الكهربائي بوحدة الجول $J$.`,
      value: PE, unit: 'J', show: `${fmt(PE)} J`, steps: [`PE_{electric} = \\frac{1}{2} C ΔV^{2}`, `PE_{electric} = \\frac{1}{2} × ${C}×10^{-6} × (${V})^{2}`, `PE_{electric} = ${fmt(PE)} J`] };
  },
  energy_q() {
    const C = pick([2, 4, 5, 8, 10]), V = pick([10, 20, 25, 50]), Q = C * V, PE = 0.5 * Q * 1e-6 * V;
    return { q: `شحنة متسعة $${Q} μC$ وفرق الجهد بين صفيحتيها $${V} V$. احسب الطاقة المختزنة فيها بوحدة الجول.`,
      value: PE, unit: 'J', show: `${fmt(PE)} J`, steps: [`PE_{electric} = \\frac{1}{2} Q ΔV`, `PE_{electric} = \\frac{1}{2} × ${Q}×10^{-6} × ${V}`, `PE_{electric} = ${fmt(PE)} J`] };
  },
  energy_x() {
    const n = pick([2, 3, 4]);
    return { q: `متسعة سعتها ثابتة، صار فرق الجهد بين صفيحتيها ${n === 2 ? 'مثلَي' : n + ' أمثال'} ما كان عليه. كم مثلًا تصير الطاقة المختزنة في مجالها الكهربائي؟`,
      value: n * n, unit: 'مثل', show: `${n * n}`, tol: 0, steps: [`PE_{electric} ∝ ΔV^{2}`, `\\frac{PE_{2}}{PE_{1}} = (${n})^{2} = ${n * n}`] };
  },
};

export function generate(key) {
  const f = G[key]; if (!f) return null;
  return { id: uid(), kind: 'numeric', source: 'gen', ...f() };
}
export const GEN_KEYS = Object.keys(G);
