    const N = pick([50, 100, 200]), B = pick([0.1, 0.2, 0.5]), A = pick([0.02, 0.05, 0.1]), w = pick([50, 100, 120]);
    const e = N * B * A * w;
    return { q: `مولد كهربائي بسيط ملفه $${N}$ لفة ومساحة وجهه $${A} m^{2}$، يدور بسرعة زاوية $${w} rad/s$ في مجال مغناطيسي منتظم كثافة فيضه $${B} T$. احسب المقدار الأعظم للقوة الدافعة الكهربائية المحتثة.`,
      value: e, unit: 'V', show: `${fmt(e)} V`, steps: [`ε_{(max)} = N B A ω`, `ε_{(max)} = ${N} × ${B} × ${A} × ${w}`, `ε_{(max)} = ${fmt(e)} V`] };
